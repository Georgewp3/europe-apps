export function buildSeedData(): AppData {
  const now = NOW();

  const universities: University[] = UNI_SEEDS.map((u) => ({
    id: `uni_${u.key}`,
    name: u.name,
    country: u.country,
    countryCode: u.countryCode,
    city: u.city,
    institutionType: /private/i.test(u.institutionLabel) ? "Private" : "Public",
    institutionLabel: u.institutionLabel,
    website: u.website,
    rankingNotes: "",
    tuitionNotes: "",
    livingCostNotes: "",
    notes: "",
    createdAt: now,
    updatedAt: now,
  }));

  const programs: Program[] = PROG_SEEDS.map((p, index) => ({
    id: `prog_${p.uni}_${index}`,
    universityId: `uni_${p.uni}`,
    name: p.name,
    degreeType: "MSc",
    field: p.field,
    specialisation: p.specialisation ?? "",
    programUrl: p.url ?? "",
    admissionsUrl: "",
    portalUrl: "",
    scholarshipsUrl: "",
    language: "English",
    durationMonths: 24,
    ects: 120,
    applicationOpenDate: p.open ?? null,
    applicationDeadline: p.deadline ?? null,
    secondDeadline: p.second ?? null,
    startDate: p.start ?? null,
    startLabel: p.startLabel ?? "",
    status: "Researching",
    priority: p.priority,
    admissionEstimate: p.estimate,
    entryRequirements: "",
    englishRequirement: "",
    greRequirement: "",
    gmatRequirement: "",
    minGrade: "",
    prerequisites: "",
    description: "",
    whyInterested: "",
    advantages: "",
    disadvantages: "",
    notes: "",
    aiRelevance: 0,
    researchStrength: 0,
    technicalDepth: 0,
    scores: emptyScores(),
    finance: defaultFinance(),
    offer: defaultOffer(),
    checklist: defaultChecklist(),
    timeline: defaultTimeline(),
    requiredDocumentIds: [],
    lastVerified: now,
    createdAt: now,
    updatedAt: now,
  }));

  return {
    schemaVersion: SCHEMA_VERSION,
    universities,
    programs,
    documents: defaultDocuments(),
    notes: [],
    settings: { ...DEFAULT_SETTINGS },
  };
}
